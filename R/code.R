code_norms_setup <- function(object) {
  a <- attr(object, "kits_args")
  if (!is.null(attr(object, "by"))) {   # 照組的常模：程式寫一個常模的（kits 的 kits_code() 會一組一組寫）
    by <- paste(attr(object, "by"), collapse = ", ")
    first <- names(attr(object, "groups"))[1]
    stop("The code is written for one norm; this norm is by ", by, " (groups: ",
         paste(names(attr(object, "groups")), collapse = ", "), "). Write the code of one group, ",
         sprintf("e.g. kits_code(attr(norm, \"groups\")[[\"%s\"]]).", first),
         call. = FALSE)
  }
  if (is.null(a)) {
    stop("This norm has no record of its settings; fit it again with kits_norms().", call. = FALSE)
  }
  c(sprintf("# Settings of kits_norms()\nages <- %s\nages_in <- %s\ndegrees <- %s\npad <- %s\ndelta_starts <- %s\nage_x <- %s\npct <- %s\n%s",
            r_vec(object$age_m, 8), r_vec(a$ages_in, 11), r_vec(a$degrees), a$pad, r_vec(a$delta_starts, 16), a$age_x,
            r_vec(a$pct, 7), if (is.null(a$delta_max)) "" else sprintf("delta_max <- %s\n", deparse(a$delta_max))),
    r"---(# 1 The data inside the ages (plus pad)
use <- is.finite(D) & is.finite(age_m) & age_m >= ages_in[1] - pad & age_m <= ages_in[2] + pad
use <- use & is.finite(age_x(age_m))
D_use <- D[use]
age_use <- age_m[use]

# x = (age_x(age) - m) / s
m <- mean(age_x(age_use))
s <- sd(age_x(age_use))
)---")
}

code_norms_tail <- r"---(# {{n}} Percentiles: P_q = mu + sigma sinh((asinh(qnorm(q / 100)) - epsilon) / delta)
P <- sapply(pct, function(q) mu + sigma * sinh((asinh(qnorm(q / 100)) - epsilon) / delta))
colnames(P) <- paste0("P", pct)
norm <- data.frame(age_m = ages, mu = mu, sigma = sigma, epsilon = epsilon, delta = delta, P)
head(norm)

# {{n2}} Same-age z: z = sinh(delta asinh((D - mu) / sigma) + epsilon), parameters interpolated between ages
#   PR = 100 pnorm(z)
z_of <- function(D, age) {
  at <- function(v) approx(ages, v, age)$y
  sinh(at(delta) * asinh((D - at(mu)) / at(sigma)) + at(epsilon))
}
z <- z_of(D, age_m)
)---"

code_delta_check <- r"---(if (max(delta) > delta_max) {
  warning("delta reaches ", round(max(delta), 2), " even at the best start. ",
          "Check the percentile curves.", call. = FALSE)
}
)---"

code_norms_cnorm <- function(object) {
  check <- if (is.null(attr(object, "kits_args")$delta_max)) NULL else code_delta_check
  c("suppressPackageStartupMessages(library(cNORM))", "", code_norms_setup(object), r"---(# 2 Fit with each start of delta and keep the largest likelihood (cNORM shash).
#   As in kits_norms(), only cNORM's warnings of the kept fit are shown: a start that is not kept
#   (often a broken local solution) can warn, for example "Hessian is not positive definite".
fit_one <- function(d0) {
  warns <- character()
  fit <- withCallingHandlers(
    cnorm.shash(age = age_x(age_use), score = D_use, mu_degree = degrees[1],
                sigma_degree = degrees[2], epsilon_degree = degrees[3],
                delta_degree = degrees[4], delta = d0, plot = FALSE),
    warning = function(w) {
      warns <<- c(warns, conditionMessage(w))
      invokeRestart("muffleWarning")
    })
  list(fit = fit, warns = warns)
}
fits <- lapply(delta_starts, fit_one)
kept <- fits[[which.min(sapply(fits, function(f) f$fit$result$value))]]
for (w in unique(kept$warns)) warning(w, call. = FALSE)
best <- kept$fit

# 3 mu, log sigma, epsilon, log delta: polynomials in x
x <- (age_x(ages) - m) / s
poly_x <- function(coef) drop(outer(x, seq_along(coef) - 1, "^") %*% coef)
mu <- poly_x(best$mu_est)
sigma <- exp(poly_x(best$sigma_est))
epsilon <- poly_x(best$epsilon_est)
delta <- exp(poly_x(best$delta_est))
)---", check, fill(code_norms_tail, n = "4", n2 = "5"))
}

