code_link <- function(object) {
  pts <- object$points
  st <- object$settings
  out <- c(sprintf("# Points: from (the scale to be converted) and to (the target scale)\nfrom <- %s\nto <- %s\nid <- %s\nitem <- %s",
                   r_vec(pts$from, 8), r_vec(pts$to, 6), r_vec(pts$id, 6), r_vec(pts$item, 8)),
           sprintf("cut <- %s\nn_boot <- %s\nseed <- %s\n", deparse(st$cut), deparse(st$n_boot), deparse(st$seed)),
           r"---(# 1 mean/sigma: new = intercept + slope x old (Kolen & Brennan's B and A)
#   slope = SD(to) / SD(from), intercept = mean(to) - slope mean(from)
mean_sigma <- function(from, to) {
  slope <- sd(to) / sd(from)
  c(intercept = mean(to) - slope * mean(from), slope = slope)
}

# 2 Screening once: e = to - (intercept0 + slope0 from); drop the points with |e| > cut SD(e);
#   then the line again
screen <- function(from, to) {
  intercept0 <- mean_sigma(from, to)[["intercept"]]
  slope0 <- mean_sigma(from, to)[["slope"]]
  e <- to - (intercept0 + slope0 * from)
  if (sd(e) < 1e-8) return(rep(FALSE, length(e)))
  abs(e) > cut * sd(e)
}
dropped <- screen(from, to)
line <- mean_sigma(from[!dropped], to[!dropped])
line
id[dropped]
)---")
  if (st$n_boot > 0) {
    out <- c(out, r"---(# 3 Linking error: resample whole items n_boot times, redo 1 and 2 each time
link_once <- function(from, to) {
  if (length(from) < 3 || sd(from) == 0 || sd(to) == 0) return(c(intercept = NA, slope = NA))
  drop <- screen(from, to)
  if (sum(!drop) < 3) return(c(intercept = NA, slope = NA))
  mean_sigma(from[!drop], to[!drop])
}
items <- unique(item)
rows <- split(seq_along(item), factor(item, levels = items))
set.seed(seed)
draws <- t(replicate(n_boot, {
  i <- unlist(rows[sample(items, replace = TRUE)], use.names = FALSE)
  link_once(from[i], to[i])
}))
ok <- is.finite(draws[, "intercept"]) & is.finite(draws[, "slope"])
c(intercept_error = sd(draws[ok, "intercept"]), slope_error = sd(draws[ok, "slope"]),
  n_failed = sum(!ok))
)---")
  }
  if (!is.null(pts$domain)) {
    out <- c(out, sprintf("# Shared slope with domain intercepts (the domains table), on the kept points\ndomain <- %s", r_vec(pts$domain, 10)),
             r"---(keep <- !dropped
mt <- ave(to[keep], domain[keep])                           # mean_d(to)
mf <- ave(from[keep], domain[keep])                         # mean_d(from)
slope_s <- sqrt(sum((to[keep] - mt)^2) / sum((from[keep] - mf)^2))
intercept_d <- tapply(to[keep], domain[keep], mean) -
  slope_s * tapply(from[keep], domain[keep], mean)
)---")
  }
  c(out, r"---(# Convert: new = intercept + slope old, and SE: new SE = slope old SE
# theta_new <- line[["intercept"]] + line[["slope"]] * theta
# se_new <- line[["slope"]] * se
)---")
}

