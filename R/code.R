code_item_dexter <- function(object) {
  thr <- object$thresholds
  fixed <- thr[thr$beta_se == 0, ]
  out <- c("library(dexter)", "", code_drop_empty, code_pcm)
  if (nrow(fixed) == 0) {
    out <- c(out, "# 1 Calibration: PCM by CML (dexter)", "fit <- fit_enorm(X)", "cf <- coef(fit)", "V <- fit$est$acov.beta", "")
  } else {
    out <- c(out,
             "# 1 Calibration: PCM by CML (dexter), with fixed items",
             sprintf("fixed <- data.frame(item_id = %s,\n                    item_score = %s,\n                    beta = %s)",
                     r_vec(fixed$item_id, 30), r_vec(fixed$item_score, 33), r_vec(fixed$beta, 27)),
             sprintf("left_out <- %s", if (length(object$left_out) > 0) r_vec(object$left_out, 12) else "character(0)"),
             "fit <- fit_enorm(X[, setdiff(colnames(X), left_out)], fixed_params = fixed[!fixed$item_id %in% left_out, ])",
             "cf <- coef(fit)", "V <- fit$est$acov.beta", "", if (length(object$left_out) > 0) code_left_out)
  }
  c(out, fill(code_thresholds, n = "2", n2 = "3"))
}

# ---- 能力 --------------------------------------------------------------------------------------------------

code_subj_dexter <- r"---(# 4 WLE (dexter): theta = argmax [log L(theta) + 1/2 log I(theta)]
parms <- cf[c("item_id", "item_score", "beta")]
# dexter's long format: one row per response, the person-wave in person_id (dexter's name)
long <- data.frame(person_id = rownames(X)[row(X)], item_id = colnames(X)[col(X)], item_score = as.vector(X))
long <- long[!is.na(long$item_score), ]
subj <- ability(long, parms, method = "WLE")
names(subj)[match(c("booklet_id", "person_id", "booklet_score"), names(subj))] <-
  c("pattern_id", "visit_id", "raw")                             # kits' names for dexter's
subj <- subj[match(rownames(X)[rowSums(!is.na(X)) > 0], subj$visit_id), ]

# dexter gives NA when its WLE does not converge: maximize the same target directly
for (j in which(!is.finite(subj$theta) | !is.finite(subj$se))) {
  its <- colnames(X)[!is.na(X[subj$visit_id[j], ])]
  r <- subj$raw[j]
  p_raw <- p_score(parms, items = its)                # P(R = r | theta); the raw score is sufficient
  info <- information(parms, items = its)            # I(theta)
  target <- function(theta) log(p_raw(theta)[, r + 1]) + 0.5 * log(info(theta))
  beta <- parms$beta[parms$item_id %in% its]
  theta <- optimize(target, c(min(beta) - 20, max(beta) + 20), maximum = TRUE, tol = 1e-10)$maximum
  I <- info(theta)
  dI <- (info(theta + 1e-4) - info(theta - 1e-4)) / 2e-4
  subj$theta[j] <- theta
  subj$se[j] <- sqrt(I + (dI / (2 * I))^2) / I        # SE = sqrt(I + (I' / 2I)^2) / I
}
)---"

