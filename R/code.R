code_screen <- function(object) {
  has_cohort <- "cohort" %in% names(object$waves)
  c(sprintf("cut <- %s", object$cut),
    if (has_cohort) "" else "cohort <- rep(NA, length(D))                            # no cohort given\n",
    r"---(# 1 Share of children at the lowest score of each (cohort x) wave: 100 x share(D = min D) >= cut leaves the wave out
D3 <- round(D, 3)
ok <- is.finite(D3) & !is.na(wave_m)
group <- paste(cohort, wave_m)
floor_pct <- tapply(D3[ok], group[ok], function(d) round(100 * mean(d == min(d)), 1))
normed_group <- floor_pct < cut
floor_pct

# 2 Whether each person-wave goes into the norm
normed <- ok & group %in% names(normed_group)[normed_group]

# 3 Ages of the norm: from the 1st percentile of age in the first wave to the 99th in the last,
#   rounded outward to half a month (kits_norm_ages)
w <- wave_m[normed]
a <- age_m[normed]
lo <- floor(quantile(a[w == min(w)], 0.01, names = FALSE) / 0.5) * 0.5
hi <- ceiling(quantile(a[w == max(w)], 0.99, names = FALSE) / 0.5) * 0.5
ages <- seq(lo, hi, by = 0.5)
)---")
}


#' The code behind a result, to copy and run
#'
#' Writes a standalone R script that redoes the computation of a result, step by step,
#' with the names of [kits_equations()]:
#' it uses the package of the engine that made the result
#' (dexter or immer; dexter for the person scores; cNORM for the norms) and base R.
#' This is "how to do this step with the original package":
#' a few lines of the package's own calls, then the conversion to the step parameters
#' on the CML origin and to the thresholds.
#' (The estimation written from scratch in RTMB is in the teaching scripts of kits.)
#'
#' The script does not need kits.
#' Each script is run in the package tests: its numbers are the same as the package's.
#'
#' What each script needs before it runs:
#' * [kits_item()], [kits()]: `X`, the response matrix given to the function.
#' * [kits_subj()]: `X`, and `cf`, the item parameters given to the function (for example `cf <- coef(item)`).
#' * [kits_norms()]: `D`, the scores given to the function as `d`, and `age_m`.
#'   (In the scripts the scores are `D`, the symbol of [kits_equations()].)
#' * [kits_norm_screen()]: `D` (the scores given as `d`), `wave_m` (and `cohort` when it was given), and `age_m` for the ages.
#' * A link: nothing (the points are written into the script).
#'
#' @param object A result: [kits_item()], [kits()], [kits_subj()], a link ([kits_linking()], [kits_linking_d()],
#'   [kits_link_line()]), [kits_norms()] or [kits_norm_screen()].
#' @param subj For a [kits_item()] result (default `FALSE`) or a [kits()] result (default `TRUE`):
#'   also write the person scores (WLE and person fit).
#' @param file Optional file to write the script to (overwritten when it exists); then the script is returned invisibly.
#' @param ... Not used.
#' @return A `kitsPreview_code` object (the lines of the script); it prints the script.
#' @examples
#' points <- data.frame(id = paste0("p", 1:5), item = paste0("p", 1:5),
#'                      from = c(-2, -1, 0, 1, 2), to = c(-1, 0, 1, 2, 3.2))
#' link <- points |>
#'   kits_link_screen() |>
#'   kits_link_line() |>
#'   kits_link_error(n_boot = 50)
#' kits_code(link)
#'
#' betas <- list(a1 = c(-1, 0), a2 = 0.5, a3 = -0.5)
#' X <- kits_sim(rnorm(200), betas, seed = 1)
#' kits_code(kits_item(X))
#'
#' # The same step with immer's own calls
#' if (requireNamespace("immer", quietly = TRUE)) {
#'   kits_code(kits_item(X, engine = "immer"))
#' }
#' @export
kits_code <- function(object, ...) UseMethod("kits_code")

#' @rdname kits_code
#' @export
kits_code.kitsPreview_item <- function(object, subj = FALSE, file = NULL, ...) {
  engine <- engine_of(object)
  code_object(c(code_header(sprintf("kits_item() with %s and base R", ENGINE_LABELS[[engine]]), "X, the response matrix given to kits_item()"),
                code_item_engine(object),
                if (subj) code_subj_after_item(engine)), file)
}

# kits() 的計分：一律是 dexter 的 WLE，步驟編號接在校準後面
code_subj_after_item <- function(engine) {
  first <- c(dexter = 4, immer = 6, ccml = 6)[[engine]]
  wle <- sub("# 4 WLE", sprintf("# %d WLE", first), code_subj_dexter, fixed = TRUE)
  c(if (engine != "dexter") "library(dexter)\n", wle,
    fill(code_person_fit, n = as.character(first + 1), n2 = as.character(first + 2), n3 = as.character(first + 3)))
}

