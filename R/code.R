#' @rdname kits_code
#' @export
kits_code.kitsPreview_link <- function(object, file = NULL, ...) {
  code_object(c(code_header("a mean/sigma link in base R", "nothing; the points are written below"), code_link(object)), file)
}

#' @rdname kits_code
#' @export
kits_code.kitsPreview_norms <- function(object, file = NULL, ...) {
  code_object(c(code_header("kits_norms() with cNORM and base R", "D (the scores given to kits_norms() as `d`) and age_m"),
                code_norms_cnorm(object)), file)
}

#' @rdname kits_code
#' @export
kits_code.kitsPreview_norm_screen <- function(object, file = NULL, ...) {
  code_object(c(code_header("kits_norm_screen() and kits_norm_ages() in base R",
                            "D (the scores given to kits_norm_screen() as `d`), wave_m (and cohort when it was given), age_m"), code_screen(object)), file)
}

#' @export
kits_code.default <- function(object, ...) {
  stop("No code for an object of class ", class(object)[1], ".", call. = FALSE)
}

#' @rdname kits_code
#' @param x A `kitsPreview_code` object.
#' @export
print.kitsPreview_code <- function(x, ...) {
  cat(x, sep = "\n")
  invisible(x)
}
