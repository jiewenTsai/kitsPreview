# 樣板裡的 {{名字}} 換成值
fill <- function(template, ...) {
  values <- list(...)
  for (n in names(values)) {
    template <- gsub(paste0("{{", n, "}}"), values[[n]], template, fixed = TRUE)
  }
  template
}

# 向量寫成 R 程式碼：數字照 17 位有效數字（讀回來是同一個數），一行最多 width 個字。
# start：同一行 c( 前面已經有幾個字（例如 "from <- " 是 8）；換行後對齊 c( 的下一個字
r_vec <- function(x, start = 0, width = 100) {
  items <- if (is.character(x)) r_string(x) else format(x, digits = 17, trim = TRUE)
  wrap_call(items, start, width)
}

# c(a, b, ...) 分成幾行，每行最多 width 個字（第一行從 start 開始）
wrap_call <- function(items, start, width) {
  if (length(items) == 0) {
    return("c()")
  }
  indent <- strrep(" ", min(start + 2, 40))
  tokens <- paste0(items, c(rep(",", length(items) - 1), ")"))
  lines <- character()
  line <- "c("
  used <- start
  for (tok in tokens) {
    sep <- if (line == "c(") "" else " "
    if (line != "c(" && line != indent && used + nchar(line) + nchar(sep) + nchar(tok) > width) {
      lines <- c(lines, line)
      line <- indent
      used <- 0
      sep <- ""
    }
    line <- paste0(line, sep, tok)
  }
  paste(c(lines, line), collapse = "\n")
}

# 字串寫成 R 程式碼，只用 ASCII（非 ASCII 的字元寫成 \uXXXX）
r_string <- function(x) {
  vapply(x, function(s) {
    code <- utf8ToInt(enc2utf8(s))
    chars <- ifelse(code > 127, sprintf("\\u%04x", code),
                    ifelse(code == 34, "\\\"", ifelse(code == 92, "\\\\", intToUtf8(code, multiple = TRUE))))
    paste0("\"", paste(chars, collapse = ""), "\"")
  }, character(1), USE.NAMES = FALSE)
}

code_header <- function(what, needs) {
  c(sprintf("# Generated by kitsPreview %s: %s", utils::packageVersion("kitsPreview"), what),
    sprintf("# Needs: %s", needs),
    "# The names follow kits_equations().",
    "")
}

code_object <- function(lines, file) {
  out <- structure(unlist(strsplit(paste(lines, collapse = "\n"), "\n", fixed = TRUE)), class = "kitsPreview_code")
  if (is.null(file)) {
    return(out)
  }
  if (!is.character(file) || length(file) != 1 || is.na(file) || !nzchar(file)) {
    stop("`file` must be one file name.", call. = FALSE)
  }
  if (!dir.exists(dirname(file))) {
    stop("The folder of `file` does not exist: ", dirname(file), ".", call. = FALSE)
  }
  writeLines(out, file)
  invisible(out)
}

code_drop_empty <- "# Items nobody answered are not calibrated\nX <- X[, colSums(!is.na(X)) > 0, drop = FALSE]\n"

