code_pcm <- r"---(# PCM: P(X = k | theta) = exp(k theta - sum_{g <= k} beta_g) / sum_h exp(h theta - sum_{g <= h} beta_g)
pcm <- function(theta, beta) {
  eta <- c(0, cumsum(theta - beta))
  exp(eta - max(eta)) / sum(exp(eta - max(eta)))
}
)---"

code_thresholds <- r"---(# {{n}} Thurstonian thresholds: P(X >= k | theta = thr) = 0.5
#   (written thr, not tau: tau is the GSED difficulty of an anchor)
p_ge <- function(theta, beta, k) sum(pcm(theta, beta)[-(1:k)])
thr <- numeric(nrow(cf))
for (r in seq_len(nrow(cf))) {
  beta <- cf$beta[cf$item_id == cf$item_id[r]]
  thr[r] <- uniroot(function(t) p_ge(t, beta, cf$item_score[r]) - 0.5, c(-40, 40), tol = 1e-10)$root
}

# {{n2}} SE of thr (delta method): sqrt(t(J) V J), J = -(dP / dbeta) / (dP / dtheta)
h <- 1e-5
thr_se <- numeric(nrow(cf))
for (r in seq_len(nrow(cf))) {
  idx <- which(cf$item_id == cf$item_id[r])
  beta <- cf$beta[idx]
  k <- cf$item_score[r]
  d_theta <- (p_ge(thr[r] + h, beta, k) - p_ge(thr[r] - h, beta, k)) / (2 * h)
  d_beta <- sapply(seq_along(beta), function(g) {
    e <- replace(numeric(length(beta)), g, h)
    (p_ge(thr[r], beta + e, k) - p_ge(thr[r], beta - e, k)) / (2 * h)
  })
  J <- -d_beta / d_theta
  thr_se[r] <- sqrt(drop(t(J) %*% V[idx, idx, drop = FALSE] %*% J))
}

thresholds <- data.frame(item_id = cf$item_id, item_score = cf$item_score, beta = cf$beta, beta_se = cf$SE_beta,
                         thr = thr, thr_se = thr_se)
thresholds <- thresholds[order(thresholds$item_id, thresholds$item_score), ]
thresholds
)---"

code_left_out <- r"---(# Fixed items left out of the calibration (no 0 score in these data): keep the fixed betas, SE 0
lo <- fixed[fixed$item_id %in% left_out, ]
cf <- rbind(cf[c("item_id", "item_score", "beta", "SE_beta")], data.frame(lo, SE_beta = 0))
V <- rbind(cbind(V, matrix(0, nrow(V), nrow(lo))), matrix(0, nrow(lo), nrow(V) + nrow(lo)))
)---"

code_person_fit <- r"---(# {{n}} raw_max: the top raw score of the items each person answered
m_i <- tapply(cf$item_score, cf$item_id, max)
subj$raw_max <- sapply(subj$visit_id, function(p) sum(m_i[colnames(X)[!is.na(X[p, ])]]))

# {{n2}} Person fit at the WLE: E = sum_k k P_k, W = sum_k k^2 P_k - E^2
#   infit = sum (x - E)^2 / sum W, outfit = mean of (x - E)^2 / W
beta_of <- split(cf$beta, cf$item_id)
subj$infit <- NA
subj$outfit <- NA
for (j in seq_len(nrow(subj))) {
  x <- X[subj$visit_id[j], ]
  x <- x[!is.na(x)]
  P <- lapply(names(x), function(i) pcm(subj$theta[j], beta_of[[i]]))
  E <- sapply(P, function(p) sum((seq_along(p) - 1) * p))
  W <- sapply(P, function(p) sum((seq_along(p) - 1)^2 * p)) - E^2
  subj$infit[j] <- sum((x - E)^2) / sum(W)
  subj$outfit[j] <- mean((x - E)^2 / W)
}

# {{n3}} flag: zero, perfect, misfit (infit or outfit > 2), ok
extreme <- subj$raw == 0 | subj$raw == subj$raw_max
subj$infit[extreme] <- NA
subj$outfit[extreme] <- NA
subj$flag <- ifelse(subj$raw == 0, "zero",
                    ifelse(subj$raw == subj$raw_max, "perfect",
                           ifelse(pmax(subj$infit, subj$outfit) > 2, "misfit", "ok")))
head(subj)
)---"

